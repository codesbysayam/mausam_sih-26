/**
 * Computes a well-balanced initial globe zoom so Earth fills ~68–76% of the
 * central viewport height across laptops, desktops, ultrawides, and mobile
 * without clipping the poles or colliding with side HUD panels.
 */
export function computeInitialGlobeZoom(
  viewportWidth: number,
  viewportHeight: number
): number {
  const safeW = Number.isFinite(viewportWidth) && viewportWidth > 0 ? viewportWidth : 1280;
  const safeH = Number.isFinite(viewportHeight) && viewportHeight > 0 ? viewportHeight : 800;
  // Reserve width for side panels on desktop (>=1024px)
  const effectiveW = safeW >= 1024 ? Math.max(360, safeW - 560) : safeW - 24;
  const effectiveH = Math.max(300, safeH - 170);
  const limitingDim = Math.min(effectiveW, effectiveH);

  if (limitingDim >= 820) return 2.3;
  if (limitingDim >= 640) return 2.15;
  if (limitingDim >= 500) return 2.0;
  if (limitingDim >= 380) return 1.8;
  return 1.45;
}

